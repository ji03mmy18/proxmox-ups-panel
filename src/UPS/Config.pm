package PVE::API2::UPS::Config;

# PVE::API2::UPS::Config
# 掛載於 /nodes/{node}/ups/config
# 提供裝置 CRUD、全域模式設定、服務重啟端點。

use strict;
use warnings;

use PVE::RESTHandler;
use PVE::JSONSchema qw(get_standard_option);
use PVE::RPCEnvironment;
use PVE::Tools qw(run_command);

use base qw(PVE::RESTHandler);

my $NUT_CONF    = '/etc/nut/nut.conf';
my $UPS_CONF    = '/etc/nut/ups.conf';
my $UPSMON_CONF = '/etc/nut/upsmon.conf';
my $UPSD_CONF   = '/etc/nut/upsd.conf';
my $UPSD_USERS  = '/etc/nut/upsd.users';

# pve-ups-notify 透過 sudo 以 root 執行（sudoers.d 已在安裝時設定）
my $NOTIFY_CMD  = '/usr/bin/sudo -n /usr/lib/pve-ups-panel/pve-ups-notify';

# ── 輔助函式 ────────────────────────────────────────────────────────────────

sub _generate_upsd_conf {
    my ($listen_addr) = @_;
    $listen_addr //= '127.0.0.1';
    return "# Generated by pve-ups-panel\nLISTEN $listen_addr 3493\nMAXCONN 1024\n";
}

sub _read_upsd_conf {
    my %conf = (listen_addr => '127.0.0.1');
    return %conf unless -f $UPSD_CONF;
    open(my $fh, '<', $UPSD_CONF) or return %conf;
    while (<$fh>) {
        $conf{listen_addr} = $1 if /^LISTEN\s+(\S+)/;
    }
    close $fh;
    return %conf;
}

# 解析 upsd.users → { username => { password, upsmon, instcmds, actions } }
sub _parse_upsd_users {
    my %users;
    return %users unless -f $UPSD_USERS;
    open(my $fh, '<', $UPSD_USERS) or return %users;
    my $cur;
    while (<$fh>) {
        chomp; s/#.*//; s/^\s+|\s+$//g; next unless $_;
        if (/^\[([^\]]+)\]/) {
            $cur = $1; $users{$cur} = {};
        } elsif ($cur) {
            $users{$cur}{password} = $1 if /^password\s*=\s*(.+)$/;
            $users{$cur}{upsmon}   = $1 if /^upsmon\s+(\S+)/;
            $users{$cur}{instcmds} = $1 if /^instcmds\s*=\s*(.+)$/i;
            $users{$cur}{actions}  = $1 if /^actions\s*=\s*(.+)$/i;
        }
    }
    close $fh;
    return %users;
}

# 讀取現有 upsmon_local 密碼，否則產生新的 32 字元隨機密碼
sub _get_or_create_local_password {
    my %users = _parse_upsd_users();
    return $users{upsmon_local}{password}
        if $users{upsmon_local} && $users{upsmon_local}{password};
    my @chars = ('a'..'z', 'A'..'Z', '0'..'9');
    return join('', map { $chars[int(rand(scalar @chars))] } 1..32);
}

sub _write_file_safe {
    my ($file, $content) = @_;
    my $tmp = "$file.tmp.$$";
    open(my $fh, '>', $tmp) or die "Cannot write $tmp: $!\n";
    print $fh $content;
    close $fh;
    rename($tmp, $file) or die "Cannot replace $file: $!\n";
}

sub _read_nut_mode {
    return 'standalone' unless -f $NUT_CONF;
    open(my $fh, '<', $NUT_CONF) or return 'standalone';
    while (<$fh>) {
        return $1 if /^\s*MODE\s*=\s*(\S+)/i;
    }
    close $fh;
    return 'standalone';
}

sub _generate_nut_conf {
    my ($mode) = @_;
    return "# Generated by pve-ups-panel\nMODE=$mode\n";
}

# 從 driver 名稱判斷裝置類型
sub _device_type {
    my ($driver) = @_;
    return 'snmp' if ($driver // '') eq 'snmp-ups';
    return 'usb';
}

# 解析 ups.conf → [{name, driver, port, ...}]
sub _parse_ups_conf {
    my @devices;
    return @devices unless -f $UPS_CONF;
    my $cur;
    open(my $fh, '<', $UPS_CONF) or return @devices;
    while (<$fh>) {
        chomp;
        s/\s*#.*$//;
        if (/^\[([^\]]+)\]/) {
            push @devices, $cur if $cur;
            $cur = { name => $1 };
        } elsif ($cur && /^\s*(\w+)\s*=\s*"?([^"]*)"?\s*$/) {
            $cur->{lc $1} = $2;
        }
    }
    push @devices, $cur if $cur;
    close $fh;
    return @devices;
}

sub _generate_ups_conf {
    my (@devices) = @_;
    my $out = "# Generated by pve-ups-panel\n\n";
    for my $d (@devices) {
        $out .= "[$d->{name}]\n";
        $out .= "    driver = $d->{driver}\n"              if $d->{driver};
        $out .= "    port = $d->{port}\n"                  if $d->{port};
        # USB 專用欄位
        $out .= "    serial = $d->{serial}\n"              if $d->{serial};
        $out .= "    vendorid = $d->{vendorid}\n"          if $d->{vendorid};
        $out .= "    productid = $d->{productid}\n"        if $d->{productid};
        # SNMP 專用欄位
        $out .= "    community = $d->{community}\n"        if $d->{community};
        $out .= "    snmp_version = $d->{snmp_version}\n"  if $d->{snmp_version};
        $out .= "    mibs = $d->{mibs}\n"                  if $d->{mibs};
        # SNMPv3 欄位（_parse_ups_conf 以 lc 儲存 key，此處對應寫回 NUT 原始大小寫）
        $out .= "    secLevel     = $d->{seclevel}\n"     if $d->{seclevel};
        $out .= "    secName      = $d->{secname}\n"      if $d->{secname};
        $out .= "    authProtocol = $d->{authprotocol}\n" if $d->{authprotocol};
        $out .= "    authPassword = $d->{authpassword}\n" if $d->{authpassword};
        $out .= "    privProtocol = $d->{privprotocol}\n" if $d->{privprotocol};
        $out .= "    privPassword = $d->{privpassword}\n" if $d->{privpassword};
        $out .= "    desc = \"$d->{desc}\"\n"              if $d->{desc};
        $out .= "\n";
    }
    return $out;
}

# 解析 upsmon.conf MONITOR 行 → [{name, host, port, username, password, montype}]
sub _parse_monitor_lines {
    my @monitors;
    return @monitors unless -f $UPSMON_CONF;
    open(my $fh, '<', $UPSMON_CONF) or return @monitors;
    while (<$fh>) {
        if (/^MONITOR\s+(\S+)\s+\d+\s+(\S+)\s+(\S+)\s+(\S+)/) {
            my ($target, $user, $pass, $montype) = ($1, $2, $3, $4);
            if ($target =~ /^([^@]+)\@([^:]+)(?::(\d+))?$/) {
                push @monitors, {
                    name     => $1,
                    host     => $2,
                    port     => defined $3 ? $3 + 0 : 3493,
                    username => $user,
                    password => $pass,
                    montype  => $montype,
                };
            }
        }
    }
    close $fh;
    return @monitors;
}

# 從 monitor 清單產生完整 upsmon.conf。
# NOTIFYCMD 固定寫入（裝置設定後 hook 即可用）；
# NOTIFYFLAG 從現有檔案保留（由 Notify.pm 在儲存通知規則時管理）。
sub _build_upsmon_conf {
    my ($monitors) = @_;

    # 只保留 NOTIFYFLAG 行（NOTIFYCMD 改為固定寫入，不依賴現有檔案）
    my @flag_lines;
    if (-f $UPSMON_CONF) {
        open(my $fh, '<', $UPSMON_CONF) or goto SKIP_FLAGS;
        while (<$fh>) {
            push @flag_lines, $_ if /^NOTIFYFLAG\s/;
        }
        close $fh;
    }
    SKIP_FLAGS:

    my $out = "# Generated by pve-ups-panel\n\n";
    for my $m (@$monitors) {
        my $target = "$m->{name}\@$m->{host}";
        $target .= ":$m->{port}" if $m->{host} ne 'localhost' && $m->{port} != 3493;
        $out .= "MONITOR $target 1 $m->{username} $m->{password} $m->{montype}\n";
    }
    $out .= <<'END';

SHUTDOWNCMD "/sbin/shutdown -h +0"
POLLFREQ 5
POLLFREQALERT 5
HOSTSYNC 15
DEADTIME 15
POWERDOWNFLAG /etc/killpower
RBWARNTIME 43200
NOCOMMWARNTIME 300
FINALDELAY 5
END
    # 固定寫入 NOTIFYCMD，確保 hook 在裝置設定後即可運作
    $out .= "\nNOTIFYCMD $NOTIFY_CMD\n";
    $out .= join('', @flag_lines) if @flag_lines;
    return $out;
}

sub _generate_upsd_users {
    my ($local_pass, $remote_user, $remote_pass) = @_;
    my $out = "# Generated by pve-ups-panel\n";
    # 本機監控帳號：master + 完整指令與設定權限（電池測試等需要）
    $out .= "[upsmon_local]\n";
    $out .= "    password = $local_pass\n";
    $out .= "    upsmon master\n";
    $out .= "    instcmds = ALL\n";
    $out .= "    actions = SET\n";
    # 可選遠端監控帳號（slave，唯讀）
    if (defined $remote_user && $remote_user ne '' &&
        defined $remote_pass && $remote_pass ne '') {
        $out .= "\n[$remote_user]\n";
        $out .= "    password = $remote_pass\n";
        $out .= "    upsmon slave\n";
    }
    return $out;
}

sub _check_device_status {
    my ($target) = @_;
    my $connected = 0;
    eval {
        open(my $fh, '-|', '/bin/upsc', $target) or die;
        while (<$fh>) { if (/^ups\.status:/) { $connected = 1; last; } }
        close $fh;
    };
    return $connected ? 'connected' : 'disconnected';
}

sub _ensure_nut_dir {
    unless (-d '/etc/nut') {
        mkdir '/etc/nut', 0750 or die "Cannot create /etc/nut: $!\n";
    }
}

sub _fix_nut_perms {
    run_command(['chown', '-R', 'root:nut', '/etc/nut'],
        errmsg => 'chown /etc/nut failed', noerr => 1);
    for my $f ($NUT_CONF, $UPS_CONF, $UPSMON_CONF, $UPSD_CONF, $UPSD_USERS) {
        chmod 0640, $f if -f $f;
    }
}

sub _restart_services {
    my ($mode) = @_;
    if (($mode // '') eq 'standalone' || ($mode // '') eq 'netserver') {
        eval { run_command(['systemctl', 'restart', 'nut-server'], errmsg => 'restart nut-server') };
        warn "nut-server restart: $@" if $@;
        sleep 1;
    }
    eval { run_command(['systemctl', 'restart', 'nut-monitor'], errmsg => 'restart nut-monitor') };
    warn "nut-monitor restart: $@" if $@;
}

